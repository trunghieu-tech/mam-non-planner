let cachedObjectives: ObjectivesDataset | null = null;

export function getSeedObjectivesDataset(): ObjectivesDataset {
  if (!cachedObjectives) {
    const raw = fs.readFileSync(SEED_OBJ_PATH, 'utf-8');
    cachedObjectives = JSON.parse(raw) as ObjectivesDataset;
  }
  return cachedObjectives;
}

export function getObjectivesDataset(): ObjectivesDataset {
  const seed = getSeedObjectivesDataset();
  if (!fs.existsSync(ANNUAL_PLANS_PATH)) return seed;
  try {
    const annualMap = JSON.parse(fs.readFileSync(ANNUAL_PLANS_PATH, 'utf-8')) as Record<
      string,
      AnnualPlanDocument
    >;
    const customList = Object.values(annualMap || {}).flatMap((ap) => ap?.customObjectives || []);
    if (customList.length === 0) return seed;
    const seen = new Set(seed.objectives.map((o) => `${o.ageGroupId}:${o.code}`));
    const merged = [...seed.objectives];
    for (const c of customList) {
      const key = `${c.ageGroupId}:${c.code}`;
      if (!seen.has(key)) {
        seen.add(key);
        merged.push(c);
      }
    }
    return {
      ...seed,
      totalObjectives: merged.length,
      objectives: merged,
    };
  } catch {
    return seed;
  }
}

export function getPlans(): WeeklyPlanDocument[] {
  if (!fs.existsSync(PLANS_PATH)) {
    const seed = fs.readFileSync(SEED_PLANS_PATH, 'utf-8');
    fs.writeFileSync(PLANS_PATH, seed, 'utf-8');
  }
  return JSON.parse(fs.readFileSync(PLANS_PATH, 'utf-8')) as WeeklyPlanDocument[];
}

export function savePlans(plans: WeeklyPlanDocument[]): void {
  fs.writeFileSync(PLANS_PATH, JSON.stringify(plans, null, 2), 'utf-8');
}

export function getPlanById(id: string): WeeklyPlanDocument | undefined {
  return getPlans().find((p) => p.id === id);
}

export function upsertPlan(plan: WeeklyPlanDocument): WeeklyPlanDocument {
  const plans = getPlans();
  const updated: WeeklyPlanDocument = {
    ...plan,
    updatedAt: new Date().toISOString(),
  };
  const idx = plans.findIndex((p) => p.id === updated.id);
  if (idx >= 0) {
    plans[idx] = updated;
  } else {
    plans.unshift(updated);
  }
  savePlans(plans);
  return updated;
}

export function deletePlan(id: string): boolean {
  const plans = getPlans();
  const filtered = plans.filter((p) => p.id !== id);
  if (filtered.length === plans.length) return false;
  savePlans(filtered);
  return true;
}

