export function getLessonTemplates(ageGroupId?: string, subjectCode?: string): SavedLessonTemplate[] {
  if (!fs.existsSync(TEMPLATES_PATH)) return [];
  try {
    const all = JSON.parse(fs.readFileSync(TEMPLATES_PATH, 'utf-8')) as SavedLessonTemplate[];
    return all.filter((t) => {
      if (ageGroupId && t.ageGroupId !== ageGroupId) return false;
      if (subjectCode && subjectCode !== 'ALL' && t.subjectCode !== subjectCode) return false;
      return true;
    });
  } catch {
    return [];
  }
}

export function saveLessonTemplate(tpl: SavedLessonTemplate): SavedLessonTemplate {
  const list = getLessonTemplates();
  const saved: SavedLessonTemplate = {
    ...tpl,
    id: tpl.id || `tpl_${Date.now()}`,
    createdAt: tpl.createdAt || new Date().toISOString(),
  };
  const idx = list.findIndex((x) => x.id === saved.id);
  if (idx >= 0) list[idx] = saved;
  else list.unshift(saved);
  fs.writeFileSync(TEMPLATES_PATH, JSON.stringify(list, null, 2), 'utf-8');
  return saved;
}

export function deleteLessonTemplate(id: string): boolean {
  const list = getLessonTemplates();
  const next = list.filter((x) => x.id !== id);
  if (next.length === list.length) return false;
  fs.writeFileSync(TEMPLATES_PATH, JSON.stringify(next, null, 2), 'utf-8');
  return true;
}

