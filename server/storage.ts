const ALL_AGE_GROUPS: AgeGroupId[] = ['NHA_TRE_24_36T', 'MAM_3_4T', 'CHOI_4_5T', 'LA_5_6T'];

export function getAnnualPlans(): Record<AgeGroupId, AnnualPlanDocument> {
  const ds = getSeedObjectivesDataset();
  let map = {} as Record<AgeGroupId, AnnualPlanDocument>;
  if (fs.existsSync(ANNUAL_PLANS_PATH)) {
    try {
      map = JSON.parse(fs.readFileSync(ANNUAL_PLANS_PATH, 'utf-8')) as Record<AgeGroupId, AnnualPlanDocument>;
    } catch {
      map = {} as Record<AgeGroupId, AnnualPlanDocument>;
    }
  }
  let changed = false;
  for (const ag of ALL_AGE_GROUPS) {
    if (!map[ag]) {
      map[ag] = buildDefaultAnnualPlan(ag, ds.objectives);
      changed = true;
    } else {
      if (!map[ag].timetable) {
        map[ag].timetable = buildDefaultTimetable(ag);
        changed = true;
      }
      map[ag].themes = map[ag].themes.map((th) => {
        if (!Array.isArray(th.assessmentMtCodes)) {
          changed = true;
          return {
            ...th,
            assessmentMtCodes: th.plannedMtCodes.slice(0, Math.min(5, th.plannedMtCodes.length)),
          };
        }
        return th;
      });
    }
  }
  if (changed) {
    fs.writeFileSync(ANNUAL_PLANS_PATH, JSON.stringify(map, null, 2), 'utf-8');
  }
  return map;
}

export function upsertAnnualPlan(ageGroupId: AgeGroupId, doc: AnnualPlanDocument): AnnualPlanDocument {
  const all = getAnnualPlans();
  const updated: AnnualPlanDocument = {
    ...doc,
    ageGroupId,
    updatedAt: new Date().toISOString(),
  };
  all[ageGroupId] = updated;
  fs.writeFileSync(ANNUAL_PLANS_PATH, JSON.stringify(all, null, 2), 'utf-8');
  return updated;
}

