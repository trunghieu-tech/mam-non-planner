let cachedWorks: LiteraryWorkItem[] | null = null;
let cachedWorksMtime = 0;

export function getLiteraryWorks(opts?: {
  ageGroupId?: string;
  kind?: string;
  q?: string;
}): LiteraryWorkItem[] {
  if (!fs.existsSync(WORKS_CORPUS_PATH)) return [];
  try {
    const stat = fs.statSync(WORKS_CORPUS_PATH);
    if (!cachedWorks || stat.mtimeMs !== cachedWorksMtime) {
      cachedWorks = JSON.parse(fs.readFileSync(WORKS_CORPUS_PATH, 'utf-8')) as LiteraryWorkItem[];
      cachedWorksMtime = stat.mtimeMs;
    }
    const norm = (s: string) =>
      (s || '')
        .replace(/đ/g, 'd')
        .replace(/Đ/g, 'D')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase();

    const qNorm = norm(opts?.q || '');
    return cachedWorks.filter((w) => {
      if (opts?.ageGroupId && !w.ageGroups.includes(opts.ageGroupId as AgeGroupId)) return false;
      if (opts?.kind && opts.kind !== 'ALL' && w.kind !== opts.kind) return false;
      if (qNorm) {
        const hay = norm(`${w.title} ${w.author} ${w.themes.join(' ')} ${w.contentText}`);
        if (!hay.includes(qNorm)) return false;
      }
      return true;
    });
  } catch {
    return [];
  }
}

