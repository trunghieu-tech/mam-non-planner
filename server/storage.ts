export function getMediaResources(opts?: {
  ageGroupId?: string;
  subjectCode?: string;
  kind?: string;
  q?: string;
}): SharedMediaResource[] {
  if (!fs.existsSync(MEDIA_PATH)) {
    fs.writeFileSync(MEDIA_PATH, JSON.stringify(DEFAULT_MEDIA_RESOURCES, null, 2), 'utf-8');
  }
  const stripVN = (s: string) =>
    (s || '')
      .replace(/đ/g, 'd')
      .replace(/Đ/g, 'D')
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase();
  try {
    const all = JSON.parse(fs.readFileSync(MEDIA_PATH, 'utf-8')) as SharedMediaResource[];
    const qNorm = stripVN((opts?.q || '').trim());
    return all.filter((m) => {
      if (opts?.ageGroupId && opts.ageGroupId !== 'ALL' && m.ageGroupId !== 'ALL' && m.ageGroupId !== opts.ageGroupId) {
        return false;
      }
      if (opts?.subjectCode && opts.subjectCode !== 'ALL' && m.subjectCode !== 'ALL' && m.subjectCode !== opts.subjectCode) {
        return false;
      }
      if (opts?.kind && opts.kind !== 'ALL' && m.kind !== opts.kind) return false;
      if (qNorm && !stripVN(`${m.title} ${m.themeName} ${m.subjectCode} ${m.author}`).includes(qNorm)) {
        return false;
      }
      return true;
    });
  } catch {
    return DEFAULT_MEDIA_RESOURCES;
  }
}

export function saveMediaResource(item: SharedMediaResource): SharedMediaResource {
  const all = getMediaResources();
  const saved: SharedMediaResource = {
    ...item,
    id: item.id || `med_${Date.now()}`,
    createdAt: item.createdAt || new Date().toISOString(),
  };
  const idx = all.findIndex((x) => x.id === saved.id);
  if (idx >= 0) all[idx] = saved;
  else all.unshift(saved);
  fs.writeFileSync(MEDIA_PATH, JSON.stringify(all, null, 2), 'utf-8');
  return saved;
}

export function deleteMediaResource(id: string): boolean {
  const all = getMediaResources();
  const next = all.filter((x) => x.id !== id);
  if (next.length === all.length) return false;
  fs.writeFileSync(MEDIA_PATH, JSON.stringify(next, null, 2), 'utf-8');
  return true;
}
