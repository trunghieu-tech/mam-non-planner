export interface CrawledKbSummary {
  available: boolean;
  totalDocs: number;
  totalLessons: number;
  totalSchools: number;
  byAgeGroup: Record<string, number>;
  updatedAt?: string;
}

export function getCrawledKbSummary(): CrawledKbSummary {
  const summaryPath = path.join(ROOT_DATA_DIR, 'kb_summary.json');
  if (fs.existsSync(summaryPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(summaryPath, 'utf-8'));
      return { available: true, ...data };
    } catch {
      // ignore partial write
    }
  }
  return {
    available: false,
    totalDocs: 0,
    totalLessons: 0,
    totalSchools: 0,
    byAgeGroup: {},
  };
}

let cachedKbByMt: Record<string, Record<string, unknown>> | null = null;
let cachedKbByMtMtime = 0;

export function getCrawledSuggestionsByMt(ageGroupId?: string, mtCode?: string): unknown {
  const kbPath = path.join(ROOT_DATA_DIR, 'kb_by_mt.json');
  if (!fs.existsSync(kbPath)) {
    return { available: false, items: [] };
  }
  try {
    const stat = fs.statSync(kbPath);
    if (!cachedKbByMt || stat.mtimeMs !== cachedKbByMtMtime) {
      cachedKbByMt = JSON.parse(fs.readFileSync(kbPath, 'utf-8')) as Record<string, Record<string, unknown>>;
      cachedKbByMtMtime = stat.mtimeMs;
    }
    const raw = cachedKbByMt;
    if (ageGroupId && mtCode) {
      const entry = raw[ageGroupId]?.[mtCode] ?? null;
      return { available: true, entry };
    }
    if (ageGroupId) {
      return { available: true, byMt: raw[ageGroupId] ?? {} };
    }
    return { available: true, all: raw };
  } catch {
    return { available: false, items: [] };
  }
}

export function searchCrawledDocs(query: string, ageGroupId?: string, mtCode?: string, limit = 30): unknown {
  const docsPath = path.join(ROOT_DATA_DIR, 'crawled_docs.json');
  if (!fs.existsSync(docsPath)) {
    return { available: false, total: 0, items: [] };
  }
  try {
    const allDocs = JSON.parse(fs.readFileSync(docsPath, 'utf-8')) as Array<{
      id: number;
      ageGroupId: string;
      schoolName: string;
      schoolHost: string;
      postTitle: string;
      filename: string;
      ext: string;
      detectedMonth: string;
      postUrl: string;
      matchedMts: Array<{ code: string; score: number; tier: string }>;
      extractedLessons: Array<{ subject: string; topic: string; type: string }>;
      snippet: string;
    }>;
    const norm = (s: string) =>
      s
        .replace(/đ/g, 'd')
        .replace(/Đ/g, 'D')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase();
    const q = norm(query || '');
    const filtered = allDocs.filter((d) => {
      if (ageGroupId && d.ageGroupId !== ageGroupId) return false;
      if (mtCode && !d.matchedMts?.some((m) => m.code === mtCode)) return false;
      if (q) {
        const hay = norm(
          `${d.postTitle} ${d.schoolName} ${d.filename} ${d.snippet} ${(d.extractedLessons || []).map((l) => `${l.subject} ${l.topic}`).join(' ')}`
        );
        if (!hay.includes(q)) return false;
      }
      return true;
    });
    return {
      available: true,
      total: filtered.length,
      items: filtered.slice(0, limit),
    };
  } catch {
    return { available: false, total: 0, items: [] };
  }
}

interface CrawledDocRecord {
  id: number;
  ageGroupId: string;
  schoolName: string;
  schoolHost: string;
  postTitle: string;
  filename: string;
  ext: string;
  detectedMonth: string;
  postUrl: string;
  matchedMts: Array<{ code: string; score: number; tier: string }>;
  extractedLessons: Array<{
    subject: string;
    topic: string;
    type: string;
    slotType?: string;
    cornerSubType?: string;
    mtCode?: string;
    score?: number;
  }>;
  snippet: string;
}

let cachedCrawledDocs: CrawledDocRecord[] | null = null;
let cachedCrawledDocsMtime = 0;

function loadCrawledDocsCached(): CrawledDocRecord[] {
  const docsPath = path.join(ROOT_DATA_DIR, 'crawled_docs.json');
  if (!fs.existsSync(docsPath)) return [];
  const stat = fs.statSync(docsPath);
  if (!cachedCrawledDocs || stat.mtimeMs !== cachedCrawledDocsMtime) {
    cachedCrawledDocs = JSON.parse(fs.readFileSync(docsPath, 'utf-8')) as CrawledDocRecord[];
    cachedCrawledDocsMtime = stat.mtimeMs;
  }
  return cachedCrawledDocs;
}

export function searchCrawledLessons(
  query: string,
  ageGroupId?: string,
  subject?: string,
  mtCode?: string,
  limit = 60,
  slotType?: string,
  cornerSubType?: string
): unknown {
  try {
    const allDocs = loadCrawledDocsCached();
    if (!allDocs.length) {
      return { available: false, total: 0, subjectCounts: {}, slotCounts: {}, cornerCounts: {}, items: [] };
    }
    const norm = (s: string) =>
      (s || '')
        .replace(/đ/g, 'd')
        .replace(/Đ/g, 'D')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase();

    const q = norm(query || '');
    const subjNorm = subject && subject !== 'ALL' && subject !== 'Tất cả' ? norm(subject) : '';
    const slotUpper = (slotType || '').trim().toUpperCase();
    const cornerNorm = cornerSubType && cornerSubType !== 'ALL' ? norm(cornerSubType) : '';
    const mtUpper = (mtCode || '').trim().toUpperCase();

    const seenTopics = new Set<string>();
    const subjectCounts: Record<string, number> = {};
    const slotCounts: Record<string, number> = {};
    const cornerCounts: Record<string, number> = {};
    const matched: Array<{
      id: string;
      docId: number;
      ageGroupId: string;
      subject: string;
      topic: string;
      type: string;
      slotType: string;
      cornerSubType: string;
      mtCode: string;
      score: number;
      schoolName: string;
      detectedMonth: string;
      postTitle: string;
      postUrl: string;
      snippet: string;
      isMainLesson: boolean;
    }> = [];

    for (const doc of allDocs) {
      if (ageGroupId && doc.ageGroupId !== ageGroupId) continue;
      for (let i = 0; i < (doc.extractedLessons || []).length; i++) {
        const les = doc.extractedLessons[i];
        const cleanTopic = (les.topic || '')
          .replace(/\s+-\s*Góc.*$/i, '')
          .replace(/\b(Th)\s+(ể)\b/g, '$1$2')
          .replace(/\b(hi)\s+(ện)\b/g, '$1$2')
          .replace(/\b(c)\s+(ảm)\b/g, '$1$2')
          .replace(/\b(x)\s+(úc)\b/g, '$1$2')
          .replace(/\s+/g, ' ')
          .trim();
        if (cleanTopic.length < 10) continue;
        // Chỉ dùng mã MT đã khớp chính xác ở cấp từng bài dạy (không ép rơi về topDocMt gây lệch mục tiêu)
        const lesMt = les.mtCode || '';
        if (mtUpper && lesMt !== mtUpper) {
          continue;
        }
        const lesSlot = (les.slotType || (les.subject === 'HĐ Góc' ? 'CORNER' : les.subject === 'HĐ Ngoài trời' ? 'OUTDOOR' : 'MAIN')).toUpperCase();
        const rawCorner = norm(les.cornerSubType || '');
        const lesCorner =
          lesSlot !== 'CORNER'
            ? ''
            : rawCorner.includes('xay dung')
            ? 'Góc xây dựng'
            : rawCorner.includes('nghe thuat') || rawCorner.includes('tao hinh') || rawCorner.includes('am nhac')
            ? 'Góc nghệ thuật'
            : rawCorner.includes('hoc tap') || rawCorner.includes('thu vien') || rawCorner.includes('sach') || rawCorner.includes('ky nang')
            ? 'Góc học tập – Thư viện'
            : rawCorner.includes('thien nhien') || rawCorner.includes('khoa hoc')
            ? 'Góc thiên nhiên'
            : 'Góc phân vai';

        const dedupeKey = `${doc.ageGroupId}|${lesSlot}|${norm(les.subject)}|${norm(cleanTopic).slice(0, 60)}`;
        if (seenTopics.has(dedupeKey)) continue;
        seenTopics.add(dedupeKey);

        if (q) {
          const hay = norm(`${les.subject} ${lesCorner} ${cleanTopic} ${lesMt} ${doc.schoolName} ${doc.detectedMonth} ${doc.postTitle}`);
          if (!hay.includes(q)) continue;
        }

        slotCounts[lesSlot] = (slotCounts[lesSlot] || 0) + 1;
        if (lesSlot === 'CORNER' && lesCorner) {
          cornerCounts[lesCorner] = (cornerCounts[lesCorner] || 0) + 1;
        }

        if (slotUpper && slotUpper !== 'ALL' && lesSlot !== slotUpper) continue;

        subjectCounts[les.subject] = (subjectCounts[les.subject] || 0) + 1;

        if (subjNorm) {
          const ls = norm(les.subject);
          const matchNbtn = subjNorm === 'nbtn' && (ls === 'nbtn' || ls === 'mtxq');
          const matchNbpb = subjNorm === 'nbpb' && (ls === 'nbpb' || ls === 'lqvt');
          if (ls !== subjNorm && !matchNbtn && !matchNbpb) {
            continue;
          }
        }
        if (cornerNorm && norm(lesCorner) !== cornerNorm) {
          continue;
        }

        const isMainLesson = lesSlot === 'MAIN';
        matched.push({
          id: `${doc.id}_${i}`,
          docId: doc.id,
          ageGroupId: doc.ageGroupId,
          subject: les.subject,
          topic: cleanTopic,
          type: les.type || 'HĐ học',
          slotType: lesSlot,
          cornerSubType: lesCorner,
          mtCode: lesMt,
          score: typeof les.score === 'number' ? les.score : doc.matchedMts?.[0]?.score || 0.5,
          schoolName: doc.schoolName,
          detectedMonth: doc.detectedMonth,
          postTitle: doc.postTitle,
          postUrl: doc.postUrl,
          snippet: doc.snippet || '',
          isMainLesson,
        });
      }
    }

    const slotOrder: Record<string, number> = { MAIN: 0, OUTDOOR: 1, AFTERNOON: 2, CORNER: 3 };
    matched.sort((a, b) => {
      const sa = slotOrder[a.slotType] ?? 9;
      const sb = slotOrder[b.slotType] ?? 9;
      if (sa !== sb) return sa - sb;
      return b.score - a.score;
    });

    return {
      available: true,
      total: matched.length,
      subjectCounts,
      slotCounts,
      cornerCounts,
      items: matched.slice(0, limit),
    };
  } catch {
    return { available: false, total: 0, subjectCounts: {}, slotCounts: {}, cornerCounts: {}, items: [] };
  }
}

